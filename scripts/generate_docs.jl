# Deterministic Markdown generation; no network, clock, or absolute machine paths.
const DOCROOT = joinpath(@__DIR__, "..", "docs")
const SCRIPT_DESCRIPTIONS = [
    "export_lineshape.jl" => "Export QTB dispersive lineshape CSV and parameter/approximation TOML.",
    "construct_JPACModel.jl" => "Export QTB and SYMM examples with the same illustrative parameters.",
    "export_phase_space.jl" => "Compare QTB, SYMM, and stable-rho phase space in CSV.",
    "plot_JPACModel.jl" => "Render the QTB example to PDF using Plots.",
    "fit_example.jl" => "Seeded synthetic regression check for the fitter.",
    "fit_ALEPH.jl" => "Fit QTB/SYMM, with and without dispersion, to the bundled ALEPH covariance data.",
    "fit_ALEPH_with_exotics.jl" => "Fit the three historical s-weighted K-matrix variants.",
    "ALEPH_bootstrap.jl" => "Fit up to 100 supplied QTB bootstrap replicas; export parameters and chi-squared.",
    "ALEPH_bootstrap_function.jl" => "Compatibility alias for the bootstrap driver.",
    "precalculate_qtb_interference.jl" => "Export complex QTB/interference grids with the historical contour (diagnostic only).",
    "isobar_analytical_structure.jl" => "Export complex isobar grids on both local branches.",
    "pole_investigation.jl" => "Search an illustrative QTB denominator zero; reports an uncertified contour diagnostic.",
    "systematic_studies_of_rho_shape_influence.jl" => "Export QTB radius variations R=3,5,7 GeV⁻¹ at fixed a1 parameters (not systematic refits).",
    "generate_docs.jl" => "Regenerate documentation Markdown; --check verifies committed output.",
]
function generate_docs(; check=false)
    pages=Dict{String,String}()
    for file in sort(readdir(joinpath(DOCROOT,"templates")))
        endswith(file,".md") || continue
        pages[file]=read(joinpath(DOCROOT,"templates",file),String)
    end
    pages["scripts.md"] = "# Script map\n\nRun `julia +1.13 --project=. scripts/NAME.jl` from the repository root. Data paths are resolved from the script location. Add `--smoke` for smaller grids or fewer replicas. The full grid and bootstrap jobs are deliberately opt-in; their smoke variants are exercised in CI. `common.jl` is shared support, not a standalone job. Outputs default to `artifacts/`.\n\n| Script | Purpose |\n|:--|:--|\n" *
        join(["| `"*name*"` | "*description*" |\n" for (name,description) in SCRIPT_DESCRIPTIONS]) *
        "\n## Migration from 2018\n\nThe original interactive worksheets are preserved in [commit e508486](https://github.com/mmikhasenko/PolePositionOfA1fromTau/tree/e508486). Their names under `tests/` remain wrappers; `pole_invesrigation.jl` forwards to the corrected spelling. Undeclared session variables, interactive widgets, and private paths have been replaced by explicit jobs. The bootstrap driver exports parameter replicas; it does not recreate the old unverified pole-bootstrap plots. The radius scan exports fixed-parameter shape variations, not the old manually edited mass/width refit study. These scopes are explicit so smoke checks cannot be mistaken for a reproduction of all paper fits.\n"
    pages["citation.md"] = "# Citation\n\nM. Mikhasenko et al. (JPAC), *Pole position of the a₁(1260) from τ-decay*, Physical Review D **98**, 096021 (2018). [DOI](https://doi.org/10.1103/PhysRevD.98.096021), [arXiv](https://arxiv.org/abs/1810.00016), [INSPIRE](https://inspirehep.net/literature/1696497).\n\nCopy the BibTeX entry from `CITATION.bib`:\n\n```bibtex\n" * read(joinpath(DOCROOT,"..","CITATION.bib"),String) * "```\n"
    mkpath(joinpath(DOCROOT,"src"))
    for (file,body) in pages
        content="<!-- Generated by scripts/generate_docs.jl; edit templates or generator. -->\n\n"*body
        path=joinpath(DOCROOT,"src",file)
        if check
            isfile(path) && read(path,String)==content || error("Stale generated page: $file")
        else
            write(path,content)
        end
    end
    println(check ? "Generated documentation is current." : "Generated $(length(pages)) Markdown pages.")
end
if abspath(PROGRAM_FILE)==@__FILE__
    generate_docs(check="--check" in ARGS)
end
